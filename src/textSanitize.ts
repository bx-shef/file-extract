/**
 * Очистка извлечённого текста документа (перенесено из ai-price-import без смены смысла).
 *
 * ЗАЧЕМ. Нулевой байт и прочие управляющие символы из чужого файла иначе уезжают дальше —
 * в базу, очередь, лог — и падают там, где о документе уже никто не думает (Postgres отвечает
 * «invalid byte sequence for encoding "UTF8": 0x00»).
 *
 * ⚠ Чистим В ОДНОЙ ТОЧКЕ — сразу после извлечения. Защита у каждого приёмника означала бы
 * несколько копий правила, которые разойдутся.
 */

/**
 * Управляющие символы C0/C1, кроме переводов строки и табуляции.
 *
 * ⚠ Записаны escape-последовательностями намеренно: литеральные управляющие символы в исходнике
 * невидимы, и правка такого класса «на глаз» неизбежно ломает диапазон.
 */
const CONTROL_CHARS = /[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F-\u009F]/g

/**
 * Сколько «читаемого» должно остаться, чтобы считать документ текстом.
 *
 * ⚠ ЧЕТЫРЕ, а не шестнадцать (перенесено из ai-price-import): ценник на один товар,
 * однострочный CSV, скан с тремя словами — законные документы, у которых меньше шестнадцати
 * непробельных знаков. Порог ловит ТОЛЬКО заведомый мусор — файл, от которого после чистки
 * не осталось ничего кроме пары знаков. Замера на корпусе коротких документов нет.
 */
export const MIN_READABLE_CHARS = 4

export interface SanitizedText {
  text: string
  /** Сколько символов вычистили. Ноль — файл был чистым. */
  removed: number
  /** Осталось ли достаточно, чтобы вообще пытаться разбирать. */
  readable: boolean
}

/**
 * Убрать из текста то, что не может нести смысла и ломает хранение.
 *
 * ⚠ Переводы строки и табуляция СОХРАНЯЮТСЯ: в них держится табличная структура документа, ради
 * которой всё и затевается. Вычистив их «заодно», мы превратили бы таблицу в кашу.
 */
export function sanitizeExtractedText(raw: string | null | undefined): SanitizedText {
  const src = String(raw ?? '')
  const text = src.replace(CONTROL_CHARS, '')
  const removed = src.length - text.length
  return { text, removed, readable: text.replace(/\s/g, '').length >= MIN_READABLE_CHARS }
}
